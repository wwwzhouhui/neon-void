import assert from 'node:assert/strict';
import { createPlayer } from '../game/src/player.js';
import { weaponHudState } from '../game/src/weapons.js';
const p = createPlayer();
const world = {colliders: [], bounds: 22};
const idle = {isDown:()=>false};
assert.equal(p.dash(0),true);
assert.equal(p.dash(0.1),false);
const before = p.state.position.z;
p.update(1/60,idle,world,1/60);
assert.ok(p.state.position.z < before);
assert.equal(p.dash(3),true);
p.state.weapons.rifle.mag = 5;
p.startReload(10);
assert.equal(weaponHudState(p,10).reloadProgress,0);
assert.ok(Math.abs(weaponHudState(p,10.625).reloadProgress-0.5)<0.0001);
p.update(1/60,idle,world,11.3);
assert.equal(p.state.weapons.rifle.mag,30);
assert.equal(p.state.reloading,false);
p.state.weapons.rifle.mag=1;p.startReload(12);p.switchWeapon('shotgun');
assert.equal(p.state.reloading,false);
p.takeDamage(200,20);assert.equal(p.state.alive,false);assert.equal(p.dash(30),false);
p.reset();assert.equal(p.state.hp,100);assert.equal(p.state.dashReadyAt,0);
assert.equal(p.state.weapons.shotgun.mag,5);
console.log('PASS: dash movement/cooldown/death/reset; simulation-time reload/progress/completion/cancellation');

p.reset();
p.state.position.set(0,0,0);
world.colliders=[{minX:-2,maxX:2,minZ:-2,maxZ:-1}];
p.dash(0);
for(let i=1;i<=12;i++) p.update(1/60,idle,world,i/60);
assert.ok(p.state.position.z >= -0.56, 'dash must not cross cover');
console.log('PASS: dash respects arena cover');

const {registerKill,chainMultiplier,resetChain}=await import('../game/src/chain.js');
const chain={};resetChain(chain);
assert.equal(chainMultiplier(chain,0),1);
let score=0;
for(let i=0;i<10;i++) score+=registerKill(chain,i,100);
assert.equal(chainMultiplier(chain,9),4);assert.equal(chain.peak,4);
assert.equal(score,2200);
assert.equal(chainMultiplier(chain,13.01),1);
assert.equal(registerKill(chain,14,100),100);assert.equal(chain.count,1);
resetChain(chain);assert.equal(chain.peak,1);
console.log('PASS: chain window, tier thresholds, score totals, expiry and reset');
